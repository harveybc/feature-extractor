"""Phase-4 extractibility: three paired arms on one feature, one TRAIN fold (plan 2026-10-06, section 2).

Data contract reused from app.univariate_temporal (lane D): standardized signal, observed_mask,
causal delta_time and known calendar encodings on an hourly grid; the forecast target never enters.

Corpus identity is pinned here (CORPORA): a parquet whose digest differs from the registry is
refused before any value is read.  Every feature resolves from the governed PS1 TRAIN parquets
(EURUSD) or the governed phase-1 ETH TRAIN parquet; PS2 batches are never read.

Fold rule (identical to the PS2 batch manifests): val = decision rows of calendar year Y inside
TRAIN; fit = [first row + 720h, val_start - 720h - 1h].  Rows after the fold's val range are never
windowed, so perturbing them cannot change a terminal (FS4-03).

Architecture: causal Conv1D encoder with temporal reduction 24 -> 12 -> 6 (latent (B, 6, D)),
symmetric decoder 6 -> 12 -> 24.  Initial weights are generated by numpy from the task seed so
RANDOM_ENCODER and TRAINED_ENCODER share bit-identical initial weights on any device.

Scoring rows (val origins with an observed value at the origin), the corruption mask and the
paired naive derive from (population, identity, feature, fold, seed) and never from the arm, so
the three arms share rows_sha256, mask_sha256 and population_n (FS4-09).
"""
